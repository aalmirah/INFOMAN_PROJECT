-- users_rights.sql
-- Access-control tables (USERS, RIGHTS, USERRIGHTS) plus the app tables that sit beside the
-- professor's schema (CUSTOMERS, PRODUCTS, REPORTS). Only database_admin is Super Admin.
-- Run AFTER schema.sql (the professor's script).
--
-- SAFE TO RE-RUN, and safe on the live Supabase project where these tables already exist:
--   * CREATE TABLE IF NOT EXISTS skips tables that are already there
--   * inserts only add rows that are missing
--   * the UPDATE only corrects emails/names that differ

CREATE TABLE IF NOT EXISTS users (
  user_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username   varchar NOT NULL UNIQUE,
  full_name  varchar NOT NULL,
  email      varchar NOT NULL UNIQUE,
  status     varchar NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
  stamp      text NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS rights (
  right_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  right_name   varchar NOT NULL UNIQUE,
  description  text,
  status       varchar NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
  stamp        text NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS userrights (
  user_right_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        bigint NOT NULL REFERENCES users (user_id)  ON DELETE CASCADE,
  right_id       bigint NOT NULL REFERENCES rights (right_id) ON DELETE CASCADE,
  status         varchar NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
  stamp          text NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (user_id, right_id)
);

CREATE TABLE IF NOT EXISTS customers (
  customer_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name    varchar NOT NULL,
  email        varchar,
  phone        varchar,
  address      text,
  status       varchar NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
  stamp        text NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS products (
  product_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_name    varchar NOT NULL,
  description     text,
  price           numeric NOT NULL DEFAULT 0 CHECK (price >= 0),
  stock_quantity  integer NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  status          varchar NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
  stamp           text NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS reports (
  report_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_name   varchar NOT NULL,
  description   text,
  generated_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status        varchar NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
  stamp         text NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

