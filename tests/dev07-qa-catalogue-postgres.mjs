import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

function docker(args, input, allowFailure = false) {
  const result = spawnSync("docker", args, { encoding: "utf8", input, timeout: 120000 });
  if (result.error || (!allowFailure && result.status !== 0)) {
    throw new Error(result.error?.message || result.stderr || `docker exited with ${result.status}`);
  }
  return result;
}

const read = (path) => readFileSync(fileURLToPath(new URL(path, import.meta.url)), "utf8");
const seed = `
  INSERT INTO public.role (name) VALUES ('User'), ('Admin'), ('Superadmin');
  INSERT INTO public.module (code, name, sort_order) VALUES
    ('CUSTOMER', 'Customer', 1), ('PRODUCT', 'Product', 2),
    ('HR', 'Human Resources', 3), ('SALES', 'Sales', 4), ('REPORTS', 'Reports', 5);
  INSERT INTO public.rights (code, module_id, action, label, sort_order)
  SELECT m.code || '_QA_ACTION_' || n, m.module_id, 'QA_ACTION_' || n, 'QA action ' || n, n
  FROM public.module m CROSS JOIN LATERAL generate_series(1, CASE m.code
    WHEN 'CUSTOMER' THEN 3 WHEN 'PRODUCT' THEN 6 WHEN 'HR' THEN 13
    WHEN 'SALES' THEN 7 WHEN 'REPORTS' THEN 7 END) n;
`;
const proposal = read("../docs/dev07_qa_catalogue_proposal.sql");
const confirmedProposal = proposal.replace(
  "REPLACE_AFTER_MANUAL_VERIFICATION",
  "jlygmihiufrlqxzsfhpf",
);

let container;
try {
  container = docker([
    "run", "--detach", "--rm", "--pull=never", "--network", "none",
    "--env", "POSTGRES_HOST_AUTH_METHOD=trust",
    "--env", "POSTGRES_DB=dev07_qa_catalogue_test", "postgres:17",
  ]).stdout.trim();
  if (!/^[a-f0-9]{64}$/.test(container)) throw new Error("Invalid container ID");

  const inspection = JSON.parse(docker(["inspect", container]).stdout)[0];
  if (inspection.HostConfig.NetworkMode !== "none"
      || Object.keys(inspection.HostConfig.PortBindings || {}).length
      || (inspection.HostConfig.Binds || []).length) {
    throw new Error("Container isolation verification failed");
  }
  let ready = false;
  for (let attempt = 0; attempt < 60; attempt += 1) {
    const logs = docker(["logs", container], undefined, true);
    if ((logs.stdout + logs.stderr).includes("PostgreSQL init process complete; ready for start up.")
        && docker(["exec", container, "pg_isready", "-U", "postgres"], undefined, true).status === 0) {
      ready = true;
      break;
    }
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 1000);
  }
  if (!ready) throw new Error("PostgreSQL did not become ready");

  function psql(database, sql, allowFailure = false) {
    return docker(
      ["exec", "-i", container, "psql", "-X", "-qAt", "-v", "ON_ERROR_STOP=1", "-U", "postgres", "-d", database],
      sql,
      allowFailure,
    );
  }
  function setup(database) {
    docker(["exec", container, "createdb", "-U", "postgres", database]);
    psql(database, `
      CREATE TABLE public.role (role_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(30) NOT NULL);
      CREATE TABLE public.module (
        module_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code varchar(20) UNIQUE NOT NULL,
        name varchar(40) NOT NULL, sort_order integer NOT NULL DEFAULT 0,
        status varchar(8) NOT NULL DEFAULT 'Active'
      );
      CREATE TABLE public.rights (
        right_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code varchar(40) UNIQUE NOT NULL,
        module_id bigint NOT NULL REFERENCES public.module(module_id), action varchar(30) NOT NULL
          CHECK (action ~ '^[A-Z][A-Z0-9_]*$'), label varchar(100) NOT NULL,
        sort_order integer NOT NULL DEFAULT 0, status varchar(8) NOT NULL DEFAULT 'Active'
      );
      CREATE TABLE public.user_permission (
        user_id bigint NOT NULL, right_id bigint NOT NULL REFERENCES public.rights(right_id),
        granted_by bigint NOT NULL, status varchar(8) NOT NULL DEFAULT 'Active',
        PRIMARY KEY (user_id, right_id)
      );
      CREATE TABLE public.audit_log (
        audit_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, table_name varchar(30) NOT NULL,
        action varchar(7) NOT NULL, record_key varchar(60), old_values jsonb, new_values jsonb,
        action_by varchar(50) NOT NULL, action_at timestamptz NOT NULL DEFAULT now()
      );
    `);
    psql(database, seed);
  }
  function snapshot(database) {
    return psql(database, "SELECT coalesce(json_agg(r ORDER BY r.right_id)::text, '[]') FROM public.rights r;").stdout.trim();
  }
  function expectBlocked(database, sql, message) {
    const before = snapshot(database);
    const result = psql(database, sql, true);
    if (result.status === 0 || !result.stderr.includes(message)) {
      throw new Error(`Expected failure "${message}": ${result.stderr}`);
    }
    if (snapshot(database) !== before) throw new Error(`Catalogue changed after failure: ${message}`);
  }

  setup("dev07_success");
  expectBlocked("dev07_success", proposal, "Manually verify");
  const beforeIds = psql("dev07_success", "SELECT string_agg(right_id || ':' || module_id || ':' || sort_order, ',' ORDER BY right_id) FROM public.rights;").stdout.trim();
  psql("dev07_success", confirmedProposal);
  const afterIds = psql("dev07_success", "SELECT string_agg(right_id || ':' || module_id || ':' || sort_order, ',' ORDER BY right_id) FROM public.rights;").stdout.trim();
  if (beforeIds !== afterIds) throw new Error("Right IDs or module ordering changed");
  const result = psql("dev07_success", "SELECT count(*) || ':' || count(*) FILTER (WHERE code LIKE '%_QA_ACTION_%') || ':' || count(*) FILTER (WHERE code = 'customers.view' AND action = 'VIEW') FROM public.rights;").stdout.trim();
  if (result !== "36:0:1") throw new Error(`Unexpected catalogue: ${result}`);
  expectBlocked("dev07_success", confirmedProposal, "does not match");
  console.log("PASS: default guard, replacement, ID preservation and rerun refusal");

  for (const [database, change, error] of [
    ["dev07_permission", "INSERT INTO public.user_permission VALUES (1, 1, 1, 'Inactive');", "Permission rows or relevant audit history"],
    ["dev07_audit", "INSERT INTO public.audit_log (table_name, action, action_by) VALUES ('user_permission', 'ADD', 'test');", "Permission rows or relevant audit history"],
    ["dev07_rights_audit", "INSERT INTO public.audit_log (table_name, action, action_by) VALUES ('rights', 'ADD', 'test');", "Permission rows or relevant audit history"],
    ["dev07_placeholder", "UPDATE public.rights SET label = 'changed' WHERE right_id = 1;", "does not match"],
    ["dev07_collision", "INSERT INTO public.module (code, name) VALUES ('OTHER', 'Other'); INSERT INTO public.rights (code, module_id, action, label) SELECT 'customers.view', module_id, 'VIEW', 'Other' FROM public.module WHERE code = 'OTHER';", "does not match"],
    ["dev07_foreign_key", "CREATE TABLE public.extra_reference (right_id bigint REFERENCES public.rights(right_id));", "Unexpected foreign key"],
    ["dev07_trigger", "CREATE FUNCTION public.test_trigger() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$; CREATE TRIGGER test_trigger BEFORE UPDATE ON public.rights FOR EACH ROW EXECUTE FUNCTION public.test_trigger();", "Unexpected rights-table trigger"],
    ["dev07_rollback", "ALTER TABLE public.rights ADD CONSTRAINT synthetic_failure CHECK (code <> 'reports.top_sales');", "synthetic_failure"],
  ]) {
    setup(database);
    psql(database, change);
    expectBlocked(database, confirmedProposal, error);
    console.log(`PASS: ${database} refusal and unchanged catalogue`);
  }
  setup("dev07_rls");
  psql("dev07_rls", `
    CREATE ROLE dev07_catalogue_rls NOLOGIN;
    GRANT USAGE ON SCHEMA public TO dev07_catalogue_rls;
    GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO dev07_catalogue_rls;
    ALTER TABLE public.rights ENABLE ROW LEVEL SECURITY;
  `);
  expectBlocked("dev07_rls", `SET ROLE dev07_catalogue_rls;\n${confirmedProposal}`, "complete row visibility");
  console.log("PASS: row-security visibility refusal and unchanged catalogue");
} finally {
  if (container && /^[a-f0-9]{64}$/.test(container)) {
    docker(["stop", container]);
  }
}
