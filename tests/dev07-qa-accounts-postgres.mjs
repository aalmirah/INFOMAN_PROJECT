import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

function docker(args, input, allowFailure = false) {
  const result = spawnSync("docker", args, { encoding: "utf8", input, timeout: 120000 });
  if (result.error || (!allowFailure && result.status !== 0)) {
    throw new Error(result.error?.message || result.stderr || `docker exited with ${result.status}`);
  }
  return result;
}

const read = (path) => readFileSync(fileURLToPath(new URL(path, import.meta.url)), "utf8");
const proposal = read("../docs/dev07_qa_accounts_proposal.sql");
const ids = [1, 2, 3, 4].map((n) => `00000000-0000-4000-8000-00000000000${n}`);
const confirmed = proposal
  .replace("REPLACE_AFTER_MANUAL_VERIFICATION", "jlygmihiufrlqxzsfhpf")
  .replace("v_confirmed_qa_only boolean := false", "v_confirmed_qa_only boolean := true")
  .replace("ARRAY[NULL, NULL, NULL, NULL]::uuid[]", `ARRAY[${ids.map((id) => `'${id}'`).join(", ")}]::uuid[]`);
const guard = read("../docs/dev07_auth_soft_delete_proposal.sql");

let container;
try {
  container = docker([
    "run", "--detach", "--rm", "--pull=never", "--network", "none",
    "--env", "POSTGRES_HOST_AUTH_METHOD=trust",
    "--env", "POSTGRES_DB=dev07_qa_accounts_test", "postgres:17",
  ]).stdout.trim();
  if (!/^[a-f0-9]{64}$/.test(container)) throw new Error("Invalid container ID");
  const inspection = JSON.parse(docker(["inspect", container]).stdout)[0];
  if (inspection.HostConfig.NetworkMode !== "none"
      || Object.keys(inspection.HostConfig.PortBindings || {}).length
      || (inspection.HostConfig.Binds || []).length) {
    throw new Error("Container isolation verification failed");
  }
  let ready = false;
  for (let attempt = 0; attempt < 60; attempt += 1) {
    const logs = docker(["logs", container], undefined, true);
    if ((logs.stdout + logs.stderr).includes("PostgreSQL init process complete; ready for start up.")
        && docker(["exec", container, "pg_isready", "-U", "postgres"], undefined, true).status === 0) {
      ready = true;
      break;
    }
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 1000);
  }
  if (!ready) throw new Error("PostgreSQL did not become ready");

  function psql(database, sql, allowFailure = false) {
    return docker(
      ["exec", "-i", container, "psql", "-X", "-qAt", "-v", "ON_ERROR_STOP=1", "-U", "postgres", "-d", database],
      sql,
      allowFailure,
    );
  }
  psql("dev07_qa_accounts_test", "CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;");
  function setup(database) {
    docker(["exec", container, "createdb", "-U", "postgres", database]);
    psql(database, `
      CREATE SCHEMA auth;
      CREATE TABLE auth.users (
        id uuid PRIMARY KEY, email text UNIQUE NOT NULL, raw_user_meta_data jsonb NOT NULL,
        deleted_at timestamptz, banned_until timestamptz, email_confirmed_at timestamptz,
        encrypted_password text
      );
      CREATE TABLE public.profiles (
        id uuid PRIMARY KEY REFERENCES auth.users(id), first_name text, last_name text,
        email text NOT NULL, role text NOT NULL DEFAULT 'user', approval_status text NOT NULL DEFAULT 'pending',
        is_active boolean NOT NULL DEFAULT true, is_blocked boolean NOT NULL DEFAULT false,
        must_change_password boolean NOT NULL DEFAULT false
      );
      CREATE TABLE public.role (
        role_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL UNIQUE, status text NOT NULL DEFAULT 'Active'
      );
      CREATE TABLE public.app_user (
        user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        auth_user_id uuid UNIQUE REFERENCES auth.users(id), first_name text NOT NULL,
        last_name text NOT NULL, email text NOT NULL, role_id bigint NOT NULL REFERENCES public.role(role_id),
        status text NOT NULL DEFAULT 'Active', is_blocked boolean NOT NULL DEFAULT false,
        must_set_password boolean NOT NULL DEFAULT true,
        FOREIGN KEY (auth_user_id) REFERENCES public.profiles(id)
      );
      CREATE UNIQUE INDEX app_user_email_lower_uidx ON public.app_user (lower(email));
      INSERT INTO public.role (name) VALUES ('User'), ('Admin'), ('Superadmin');
      INSERT INTO auth.users (id, email, raw_user_meta_data, email_confirmed_at, encrypted_password)
      SELECT id::uuid, 'fixture' || n || '@example.invalid', '{"dev07_qa_fixture":"true"}'::jsonb,
             now(), 'synthetic-hash'
      FROM unnest(ARRAY[${ids.map((id) => `'${id}'`).join(", ")}]) WITH ORDINALITY AS x(id, n);
      INSERT INTO public.profiles (id, email) SELECT id, email FROM auth.users;
    `);
    psql(database, guard);
  }
  function snapshot(database) {
    return psql(database, `
      SELECT (SELECT json_agg(p ORDER BY p.id)::text FROM public.profiles p) || ':' ||
             coalesce((SELECT json_agg(u ORDER BY u.user_id)::text FROM public.app_user u), '[]');
    `).stdout.trim();
  }
  function expectBlocked(database, sql, message) {
    const before = snapshot(database);
    const result = psql(database, sql, true);
    if (result.status === 0 || !result.stderr.includes(message)) {
      throw new Error(`Expected failure "${message}": ${result.stderr}`);
    }
    if (snapshot(database) !== before) throw new Error(`Partial changes after failure: ${message}`);
  }

  setup("dev07_accounts_success");
  expectBlocked("dev07_accounts_success", proposal, "Manually verify");
  const projectConfirmed = proposal.replace("REPLACE_AFTER_MANUAL_VERIFICATION", "jlygmihiufrlqxzsfhpf");
  expectBlocked("dev07_accounts_success", projectConfirmed, "QA-only");
  expectBlocked("dev07_accounts_success", projectConfirmed.replace("v_confirmed_qa_only boolean := false", "v_confirmed_qa_only boolean := true"), "four distinct");
  psql("dev07_accounts_success", confirmed);
  const verified = psql("dev07_accounts_success", `
    SELECT string_agg(p.role || ':' || r.name, ',' ORDER BY p.id)
    FROM public.profiles p JOIN public.app_user u ON u.auth_user_id = p.id
    JOIN public.role r ON r.role_id = u.role_id
    WHERE p.approval_status = 'approved' AND u.status = 'Active';
  `).stdout.trim();
  if (verified !== "superadmin:Superadmin,admin:Admin,admin:Admin,user:User") {
    throw new Error(`Unexpected linked roles: ${verified}`);
  }
  expectBlocked("dev07_accounts_success", confirmed, "not a new eligible synthetic QA profile");
  console.log("PASS: fail-closed defaults, roles, UUID links, actual Auth guards and rerun refusal");

  for (const [database, change, error] of [
    ["dev07_accounts_pending", "UPDATE public.profiles SET approval_status = 'approved' WHERE id = '" + ids[3] + "';", "not a new eligible synthetic QA profile"],
    ["dev07_accounts_password", "UPDATE auth.users SET encrypted_password = NULL WHERE id = '" + ids[3] + "';", "not a new eligible synthetic QA profile"],
    ["dev07_accounts_role", "UPDATE public.role SET status = 'Inactive' WHERE name = 'Admin';", "Expected exactly one active ERP role"],
    ["dev07_accounts_conflict", "INSERT INTO public.app_user (auth_user_id, first_name, last_name, email, role_id) SELECT id, 'QA', 'Existing', email, 1 FROM auth.users WHERE id = '" + ids[3] + "';", "Existing ERP account conflicts"],
    ["dev07_accounts_rollback", "ALTER TABLE public.app_user ADD CONSTRAINT synthetic_failure CHECK (last_name <> 'User');", "synthetic_failure"],
  ]) {
    setup(database);
    psql(database, change);
    expectBlocked(database, confirmed, error);
    console.log(`PASS: ${database} refusal and unchanged accounts`);
  }
} finally {
  if (container && /^[a-f0-9]{64}$/.test(container)) docker(["stop", container]);
}
