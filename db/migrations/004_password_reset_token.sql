CREATE TABLE password_reset_token (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  token_hash varchar(64) NOT NULL,
  purpose varchar(20) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  requested_ip inet,
  status varchar(8) NOT NULL DEFAULT 'Active'
    CONSTRAINT password_reset_token_status_check
      CHECK (status IN ('Active', 'Inactive')),
  stamp varchar(80) NOT NULL DEFAULT (
    'CREATED system ' ||
    to_char(clock_timestamp() AT TIME ZONE 'Asia/Manila', 'YYYY-MM-DD HH12:MI AM')
  ),
  CONSTRAINT password_reset_token_user_fk FOREIGN KEY (user_id)
    REFERENCES app_user (user_id) ON DELETE RESTRICT,
  CONSTRAINT password_reset_token_purpose_check
    CHECK (purpose IN ('set_password', 'reset_password')),
  CONSTRAINT password_reset_token_hash_check
    CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT password_reset_token_expiry_check
    CHECK (expires_at > created_at)
);

CREATE UNIQUE INDEX password_reset_token_hash_uidx
  ON password_reset_token (token_hash);
CREATE INDEX password_reset_token_expires_at_idx
  ON password_reset_token (expires_at);
CREATE UNIQUE INDEX password_reset_token_one_open_per_purpose_uidx
  ON password_reset_token (user_id, purpose)
  WHERE used_at IS NULL AND status = 'Active';

CREATE FUNCTION maintain_password_reset_token() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF (NEW.user_id, NEW.token_hash, NEW.purpose, NEW.created_at, NEW.expires_at, NEW.requested_ip)
      IS DISTINCT FROM
       (OLD.user_id, OLD.token_hash, OLD.purpose, OLD.created_at, OLD.expires_at, OLD.requested_ip) THEN
      RAISE EXCEPTION 'Password reset token identity and expiry fields are immutable.';
    END IF;

    IF OLD.used_at IS NOT NULL AND NEW.used_at IS NULL THEN
      RAISE EXCEPTION 'A used password reset token cannot be made unused again.';
    END IF;

    IF OLD.status = 'Inactive' AND NEW.status = 'Active' THEN
      RAISE EXCEPTION 'An inactive password reset token cannot be reactivated.';
    END IF;

    NEW.stamp := 'UPDATED system ' ||
      to_char(clock_timestamp() AT TIME ZONE 'Asia/Manila', 'YYYY-MM-DD HH12:MI AM');
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER password_reset_token_maintain_before_update
BEFORE UPDATE ON password_reset_token
FOR EACH ROW EXECUTE FUNCTION maintain_password_reset_token();

COMMENT ON TABLE password_reset_token IS
  'Stores only SHA-256 token hashes. used_at is the one-time-use marker; cleanup may delete used or expired rows.';
COMMENT ON COLUMN password_reset_token.used_at IS
  'NULL means unused; the timestamp records when the token was consumed and cannot be cleared.';
COMMENT ON INDEX password_reset_token_one_open_per_purpose_uidx IS
  'At most one Active unused row per user and purpose. Token issuance must inactivate the prior row in the same transaction.';
