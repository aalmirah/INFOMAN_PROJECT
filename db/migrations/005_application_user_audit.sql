CREATE TABLE IF NOT EXISTS audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name varchar(63) NOT NULL,
  record_key text NOT NULL,
  action text NOT NULL,
  app_user text NOT NULL,
  db_user text NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  old_values jsonb,
  new_values jsonb,
  CONSTRAINT audit_log_action_check
    CHECK (action IN ('CREATED', 'EDITED', 'DELETED', 'RESTORED'))
);

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'audit_log' AND column_name = 'audit_id'
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'audit_log' AND column_name = 'id'
  ) THEN
    ALTER TABLE public.audit_log RENAME COLUMN audit_id TO id;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'audit_log' AND column_name = 'action_by'
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'audit_log' AND column_name = 'app_user'
  ) THEN
    ALTER TABLE public.audit_log RENAME COLUMN action_by TO app_user;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'audit_log' AND column_name = 'action_at'
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'audit_log' AND column_name = 'occurred_at'
  ) THEN
    ALTER TABLE public.audit_log RENAME COLUMN action_at TO occurred_at;
  END IF;
END;
$$;

ALTER TABLE public.audit_log
  ADD COLUMN IF NOT EXISTS table_name varchar(63),
  ADD COLUMN IF NOT EXISTS record_key text,
  ADD COLUMN IF NOT EXISTS action text,
  ADD COLUMN IF NOT EXISTS app_user text,
  ADD COLUMN IF NOT EXISTS db_user text,
  ADD COLUMN IF NOT EXISTS occurred_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  ADD COLUMN IF NOT EXISTS old_values jsonb,
  ADD COLUMN IF NOT EXISTS new_values jsonb;

DO $$
DECLARE
  constraint_row record;
BEGIN
  FOR constraint_row IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'public.audit_log'::regclass
      AND contype = 'c'
  LOOP
    EXECUTE format('ALTER TABLE public.audit_log DROP CONSTRAINT %I', constraint_row.conname);
  END LOOP;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'audit_log' AND column_name = 'action'
      AND data_type <> 'text'
  ) THEN
    ALTER TABLE public.audit_log ALTER COLUMN action TYPE text USING action::text;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'audit_log' AND column_name = 'app_user'
      AND is_nullable = 'YES'
  ) THEN
    UPDATE public.audit_log SET app_user = 'system' WHERE app_user IS NULL OR btrim(app_user) = '';
  END IF;

  UPDATE public.audit_log SET table_name = 'unknown' WHERE table_name IS NULL;
  UPDATE public.audit_log SET record_key = '' WHERE record_key IS NULL;
  UPDATE public.audit_log SET db_user = 'unknown' WHERE db_user IS NULL OR btrim(db_user) = '';

  UPDATE public.audit_log
  SET action = CASE action
    WHEN 'ADD' THEN 'CREATED'
    WHEN 'EDIT' THEN 'EDITED'
    WHEN 'DELETE' THEN 'DELETED'
    WHEN 'RESTORE' THEN 'RESTORED'
    ELSE action
  END;

  ALTER TABLE public.audit_log
    ALTER COLUMN table_name TYPE varchar(63),
    ALTER COLUMN record_key TYPE text,
    ALTER COLUMN app_user TYPE text USING app_user::text,
    ALTER COLUMN db_user TYPE text USING db_user::text,
    ALTER COLUMN table_name SET NOT NULL,
    ALTER COLUMN record_key SET NOT NULL,
    ALTER COLUMN app_user SET DEFAULT 'system',
    ALTER COLUMN app_user SET NOT NULL,
    ALTER COLUMN db_user SET DEFAULT 'unknown',
    ALTER COLUMN db_user SET NOT NULL,
    ALTER COLUMN occurred_at SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN occurred_at SET NOT NULL,
    ALTER COLUMN action SET NOT NULL;

  ALTER TABLE public.audit_log
    ADD CONSTRAINT audit_log_action_check
      CHECK (action IN ('CREATED', 'EDITED', 'DELETED', 'RESTORED'));
END;
$$;

COMMENT ON TABLE public.audit_log IS
  'Append-only audit history. app_user is the transaction-local application identity; db_user retains the PostgreSQL connection identity.';

CREATE OR REPLACE FUNCTION public.audit_user() RETURNS text
LANGUAGE sql STABLE
SET search_path = pg_catalog, public
AS $$
  SELECT COALESCE(NULLIF(btrim(current_setting('app.current_user', true)), ''), 'system');
$$;

CREATE OR REPLACE FUNCTION public.audit_stamp(p_action text) RETURNS text
LANGUAGE sql STABLE
SET search_path = pg_catalog, public
AS $$
  SELECT p_action || ' ' || public.audit_user() || ' ' ||
         to_char(CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Manila', 'YYYY-MM-DD FMHH12:MI AM');
$$;

CREATE OR REPLACE FUNCTION public.set_audit_stamp() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.stamp := public.audit_stamp('CREATED');
  ELSIF (to_jsonb(NEW) - 'stamp') IS NOT DISTINCT FROM (to_jsonb(OLD) - 'stamp') THEN
    NEW.stamp := OLD.stamp;
  ELSIF OLD.status = 'Active' AND NEW.status = 'Inactive' THEN
    NEW.stamp := public.audit_stamp('DELETED');
  ELSIF OLD.status = 'Inactive' AND NEW.status = 'Active' THEN
    NEW.stamp := public.audit_stamp('RESTORED');
  ELSE
    NEW.stamp := public.audit_stamp('EDITED');
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.write_audit_log() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  row_json jsonb;
  old_json jsonb;
  new_json jsonb;
  row_key text;
  event_action text;
  key_name text;
  key_position integer := 0;
BEGIN
  IF TG_OP = 'INSERT' THEN
    row_json := to_jsonb(NEW) - ARRAY['password_hash', 'token_hash'];
    event_action := 'CREATED';
  ELSE
    old_json := to_jsonb(OLD);
    new_json := to_jsonb(NEW);
    IF (old_json - 'stamp') IS NOT DISTINCT FROM (new_json - 'stamp') THEN
      RETURN NULL;
    END IF;

    IF OLD.status = 'Active' AND NEW.status = 'Inactive' THEN
      event_action := 'DELETED';
    ELSIF OLD.status = 'Inactive' AND NEW.status = 'Active' THEN
      event_action := 'RESTORED';
    ELSE
      event_action := 'EDITED';
    END IF;

    old_json := old_json - ARRAY['password_hash', 'token_hash'];
    new_json := new_json - ARRAY['password_hash', 'token_hash'];
  END IF;

  FOREACH key_name IN ARRAY TG_ARGV LOOP
    key_position := key_position + 1;
    IF key_position > 1 THEN
      row_key := COALESCE(row_key || '|', '');
    END IF;
    row_key := COALESCE(row_key, '') || COALESCE(
      CASE WHEN TG_OP = 'INSERT' THEN row_json ELSE new_json END ->> key_name,
      ''
    );
  END LOOP;

  INSERT INTO public.audit_log
    (table_name, record_key, action, app_user, db_user, old_values, new_values)
  VALUES (
    TG_TABLE_NAME,
    COALESCE(row_key, ''),
    event_action,
    public.audit_user(),
    session_user::text,
    old_json,
    CASE WHEN TG_OP = 'INSERT' THEN row_json ELSE new_json END
  );
  RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.protect_audit_log() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  RAISE EXCEPTION 'audit_log is append-only.';
END;
$$;

DROP TRIGGER IF EXISTS audit_log_protect_row ON public.audit_log;
DROP TRIGGER IF EXISTS audit_log_protect_truncate ON public.audit_log;

CREATE TRIGGER audit_log_protect_row
BEFORE UPDATE OR DELETE ON public.audit_log
FOR EACH ROW EXECUTE FUNCTION public.protect_audit_log();

CREATE TRIGGER audit_log_protect_truncate
BEFORE TRUNCATE ON public.audit_log
FOR EACH STATEMENT EXECUTE FUNCTION public.protect_audit_log();

REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.audit_log FROM PUBLIC;

DO $$
DECLARE
  table_config record;
  old_trigger record;
  trigger_arguments text;
  key_columns text[];
BEGIN
  FOR old_trigger IN
    SELECT trigger_row.tgname, table_row.relname
    FROM pg_trigger trigger_row
    JOIN pg_class table_row ON table_row.oid = trigger_row.tgrelid
    JOIN pg_namespace namespace_row ON namespace_row.oid = table_row.relnamespace
    JOIN pg_proc function_row ON function_row.oid = trigger_row.tgfoid
    WHERE namespace_row.nspname = 'public'
      AND NOT trigger_row.tgisinternal
      AND function_row.proname IN ('trg_set_stamp', 'trg_audit_log')
  LOOP
    EXECUTE format('DROP TRIGGER %I ON public.%I', old_trigger.tgname, old_trigger.relname);
  END LOOP;

  FOR table_config IN
    SELECT table_row.oid, table_row.relname AS table_name
    FROM pg_class table_row
    JOIN pg_namespace namespace_row ON namespace_row.oid = table_row.relnamespace
    WHERE namespace_row.nspname = 'public'
      AND table_row.relkind IN ('r', 'p')
      AND EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = table_row.relname
          AND column_name = 'status'
      )
      AND EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = table_row.relname
          AND column_name = 'stamp'
      )
    ORDER BY table_row.relname
  LOOP
    SELECT array_agg(attribute_row.attname::text ORDER BY key_row.ordinality)
      INTO key_columns
      FROM pg_index primary_key
      CROSS JOIN LATERAL unnest(primary_key.indkey) WITH ORDINALITY
        AS key_row(attribute_number, ordinality)
      JOIN pg_attribute attribute_row
        ON attribute_row.attrelid = primary_key.indrelid
       AND attribute_row.attnum = key_row.attribute_number
      WHERE primary_key.indrelid = table_config.oid
        AND primary_key.indisprimary;

    IF key_columns IS NULL THEN
      RAISE EXCEPTION 'Cannot attach audit triggers: public.% has status/stamp columns but no primary key.',
        table_config.table_name;
    END IF;

    SELECT string_agg(quote_literal(column_name), ',')
      INTO trigger_arguments
      FROM unnest(key_columns) AS key_row(column_name);

    EXECUTE format(
      'ALTER TABLE public.%I ALTER COLUMN stamp TYPE varchar(320)',
      table_config.table_name
    );
    EXECUTE format(
      'DROP TRIGGER IF EXISTS zz_audit_stamp ON public.%I',
      table_config.table_name
    );
    EXECUTE format(
      'DROP TRIGGER IF EXISTS zz_audit_log ON public.%I',
      table_config.table_name
    );
    EXECUTE format(
      'CREATE TRIGGER zz_audit_stamp BEFORE INSERT OR UPDATE ON public.%I
       FOR EACH ROW EXECUTE FUNCTION public.set_audit_stamp()',
      table_config.table_name
    );
    EXECUTE format(
      'CREATE TRIGGER zz_audit_log AFTER INSERT OR UPDATE ON public.%I
       FOR EACH ROW EXECUTE FUNCTION public.write_audit_log(%s)',
      table_config.table_name,
      trigger_arguments
    );
  END LOOP;
END;
$$;
