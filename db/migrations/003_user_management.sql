CREATE VIEW v_user_effective_rights AS
SELECT
  u.user_id,
  u.email,
  m.module_id,
  m.code AS module_code,
  m.name AS module_name,
  r.right_id,
  r.code AS right_code,
  r.action,
  r.label,
  (
    u.status = 'Active'
    AND NOT u.is_blocked
    AND role.status = 'Active'
    AND (
      role.name = 'Superadmin'
      OR EXISTS (
        SELECT 1
        FROM user_permission up
        WHERE up.user_id = u.user_id
          AND up.right_id = r.right_id
          AND up.status = 'Active'
      )
    )
  ) AS granted
FROM app_user u
JOIN role ON role.role_id = u.role_id
CROSS JOIN module m
JOIN rights r ON r.module_id = m.module_id
WHERE m.status = 'Active'
  AND r.status = 'Active';

CREATE VIEW v_module_right_counts AS
SELECT m.code AS module_code,
       m.name AS module_name,
       count(r.right_id)::integer AS active_right_count
FROM module m
LEFT JOIN rights r
  ON r.module_id = m.module_id
 AND r.status = 'Active'
WHERE m.status = 'Active'
GROUP BY m.module_id, m.code, m.name, m.sort_order
ORDER BY m.sort_order;

