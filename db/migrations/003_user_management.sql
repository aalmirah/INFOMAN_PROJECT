CREATE TABLE role (
  role_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(30) NOT NULL UNIQUE,
  description varchar(200),
  status varchar(8) NOT NULL DEFAULT 'Active'
    CONSTRAINT role_status_check CHECK (status IN ('Active', 'Inactive')),
  stamp varchar(80) NOT NULL DEFAULT (
    'CREATED system ' ||
    to_char(clock_timestamp() AT TIME ZONE 'Asia/Manila', 'YYYY-MM-DD HH12:MI AM')
  )
);

CREATE TABLE module (
  module_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(20) NOT NULL UNIQUE,
  name varchar(40) NOT NULL UNIQUE,
  sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  status varchar(8) NOT NULL DEFAULT 'Active'
    CONSTRAINT module_status_check CHECK (status IN ('Active', 'Inactive')),
  stamp varchar(80) NOT NULL DEFAULT (
    'CREATED system ' ||
    to_char(clock_timestamp() AT TIME ZONE 'Asia/Manila', 'YYYY-MM-DD HH12:MI AM')
  )
);

CREATE TABLE rights (
  right_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(40) NOT NULL UNIQUE,
  module_id bigint NOT NULL,
  action varchar(30) NOT NULL,
  label varchar(100) NOT NULL,
  sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  status varchar(8) NOT NULL DEFAULT 'Active'
    CONSTRAINT rights_status_check CHECK (status IN ('Active', 'Inactive')),
  stamp varchar(80) NOT NULL DEFAULT (
    'CREATED system ' ||
    to_char(clock_timestamp() AT TIME ZONE 'Asia/Manila', 'YYYY-MM-DD HH12:MI AM')
  ),
  CONSTRAINT rights_module_fk FOREIGN KEY (module_id)
    REFERENCES module (module_id) ON DELETE RESTRICT,
  CONSTRAINT rights_action_check CHECK (action ~ '^[A-Z][A-Z0-9_]*$')
);

CREATE TABLE app_user (
  user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name varchar(50) NOT NULL,
  last_name varchar(50) NOT NULL,
  email varchar(254) NOT NULL,
  password_hash varchar(255),
  role_id bigint NOT NULL,
  employee_empno varchar(5),
  is_blocked boolean NOT NULL DEFAULT false,
  must_set_password boolean NOT NULL DEFAULT true,
  failed_login_count integer NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
  locked_until timestamptz,
  last_login_at timestamptz,
  status varchar(8) NOT NULL DEFAULT 'Active'
    CONSTRAINT app_user_status_check CHECK (status IN ('Active', 'Inactive')),
  stamp varchar(80) NOT NULL DEFAULT (
    'CREATED system ' ||
    to_char(clock_timestamp() AT TIME ZONE 'Asia/Manila', 'YYYY-MM-DD HH12:MI AM')
  ),
  CONSTRAINT app_user_email_lowercase_check CHECK (email = lower(email)),
  CONSTRAINT app_user_role_fk FOREIGN KEY (role_id)
    REFERENCES role (role_id) ON DELETE RESTRICT,
  CONSTRAINT app_user_employee_fk FOREIGN KEY (employee_empno)
    REFERENCES employee (empno) ON DELETE RESTRICT
);

CREATE TABLE user_permission (
  user_id bigint NOT NULL,
  right_id bigint NOT NULL,
  granted_by bigint NOT NULL,
  granted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status varchar(8) NOT NULL DEFAULT 'Active'
    CONSTRAINT user_permission_status_check CHECK (status IN ('Active', 'Inactive')),
  stamp varchar(80) NOT NULL DEFAULT (
    'CREATED system ' ||
    to_char(clock_timestamp() AT TIME ZONE 'Asia/Manila', 'YYYY-MM-DD HH12:MI AM')
  ),
  PRIMARY KEY (user_id, right_id),
  CONSTRAINT user_permission_user_fk FOREIGN KEY (user_id)
    REFERENCES app_user (user_id) ON DELETE RESTRICT,
  CONSTRAINT user_permission_right_fk FOREIGN KEY (right_id)
    REFERENCES rights (right_id) ON DELETE RESTRICT,
  CONSTRAINT user_permission_granted_by_fk FOREIGN KEY (granted_by)
    REFERENCES app_user (user_id) ON DELETE RESTRICT
);

