CREATE FUNCTION set_app_user_defaults() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  NEW.email := lower(btrim(NEW.email));

  IF NEW.role_id IS NULL THEN
    SELECT role_id
      INTO NEW.role_id
      FROM public.role
      WHERE name = 'User' AND status = 'Active';

    IF NEW.role_id IS NULL THEN
      RAISE EXCEPTION 'Cannot create app_user: active default User role is missing.';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER app_user_defaults_before_write
BEFORE INSERT OR UPDATE OF email, role_id ON app_user
FOR EACH ROW EXECUTE FUNCTION set_app_user_defaults();

CREATE FUNCTION enforce_user_permission_write() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  actor_id bigint;
  actor_role_name text;
  actor_user_status text;
  actor_blocked boolean;
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Physical deletion of user_permission is forbidden; set status = Inactive.';
  END IF;

  IF TG_OP = 'UPDATE' AND (NEW.user_id, NEW.right_id) IS DISTINCT FROM (OLD.user_id, OLD.right_id) THEN
    RAISE EXCEPTION 'user_permission keys are immutable; deactivate the old row instead.';
  END IF;

  BEGIN
    actor_id := NULLIF(current_setting('app.actor_user_id', true), '')::bigint;
  EXCEPTION
    WHEN invalid_text_representation THEN
      RAISE EXCEPTION 'Invalid app.actor_user_id setting.';
  END;

  IF actor_id IS NULL THEN
    RAISE EXCEPTION 'Set transaction-local app.actor_user_id after authenticating the acting app_user.';
  END IF;

  SELECT r.name, u.status, u.is_blocked
    INTO actor_role_name, actor_user_status, actor_blocked
    FROM public.app_user u
    JOIN public.role r ON r.role_id = u.role_id AND r.status = 'Active'
    WHERE u.user_id = actor_id;

  IF NOT FOUND
    OR actor_user_status <> 'Active'
    OR actor_blocked
    OR actor_role_name NOT IN ('Admin', 'Superadmin') THEN
    RAISE EXCEPTION 'Only an active, unblocked Admin or Superadmin may change user permissions.';
  END IF;

  IF TG_OP = 'INSERT' THEN
    NEW.granted_by := actor_id;
    NEW.granted_at := CURRENT_TIMESTAMP;
  ELSE
    NEW.granted_by := OLD.granted_by;
    NEW.granted_at := OLD.granted_at;
    NEW.stamp := 'UPDATED system ' ||
      to_char(clock_timestamp() AT TIME ZONE 'Asia/Manila', 'YYYY-MM-DD HH12:MI AM');
    IF NEW.status = 'Active' AND OLD.status IS DISTINCT FROM 'Active' THEN
      NEW.granted_by := actor_id;
      NEW.granted_at := CURRENT_TIMESTAMP;
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER user_permission_write_guard
BEFORE INSERT OR UPDATE OR DELETE ON user_permission
FOR EACH ROW EXECUTE FUNCTION enforce_user_permission_write();

